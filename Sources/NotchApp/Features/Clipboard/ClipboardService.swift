import AppKit

struct ClipboardItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let date: Date
}

/// Remembers recently copied text (in memory only; nothing is saved to disk).
///
/// macOS has no "clipboard changed" notification, so like every clipboard
/// manager we check the pasteboard's change counter once a second. That's a
/// single cheap number comparison.
@MainActor
final class ClipboardService: ObservableObject {
    @Published private(set) var items: [ClipboardItem] = []

    let maxItems = 20
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount

    /// Password managers mark secrets with these types so clipboard tools skip them.
    /// See http://nspasteboard.org
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 1, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.checkPasteboard() }
        }
        timer.tolerance = 0.5 // lets macOS batch this wake-up with others
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        items.removeAll()
    }

    func clear() {
        items.removeAll()
    }

    /// Puts an item back on the clipboard (and moves it to the top).
    func copy(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        add(item.text)
    }

    private func checkPasteboard() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return }
        add(String(text.prefix(10_000)))
    }

    private func add(_ text: String) {
        // Copying something already in the list just moves it to the top.
        if let index = items.firstIndex(where: { $0.text == text }) {
            items.insert(items.remove(at: index), at: 0)
            return
        }
        items.insert(ClipboardItem(text: text, date: Date()), at: 0)
        if items.count > maxItems { items.removeLast(items.count - maxItems) }
    }
}

#if DEBUG
extension ClipboardService {
    func showPreview(_ texts: [String]) {
        items = texts.map { ClipboardItem(text: $0, date: Date()) }
    }
}
#endif
